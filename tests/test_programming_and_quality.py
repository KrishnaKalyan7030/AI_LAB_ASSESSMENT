"""Feature B (programming assistant) and Feature C (code-quality review)."""
import json

from tests.conftest import assert_rate_limited_message
from tests.fakes import RateLimitError

ASSIST_TOOL = "record_programming_feedback"
QUALITY_TOOL = "record_code_review"
STUDENT3_SUBMISSION = 3  # seeded DFS-style BFS attempt by student3 (fails tests)


def _assist_payload(**overrides):
    payload = {
        "code_explanation": "Your function walks the graph using a stack.",
        "failed_test_explanations": [{"test": "Test 1", "explanation": "A stack visits C before B."}],
        "likely_logical_errors": ["Using a stack (LIFO) gives DFS order, not BFS."],
        "improvement_suggestions": ["Use collections.deque and popleft()."],
        "encouragement": "Good start!",
    }
    payload.update(overrides)
    return payload


def _login_student3(app):
    from tests.conftest import assert_rate_limited_message, Client

    c = Client(app.test_client())
    c.login("student3")
    return c


def test_assistant_receives_engine_results_and_hides_hidden_inputs(app, fake_claude):
    c = _login_student3(app)
    fake_claude.set(ASSIST_TOOL, _assist_payload())
    resp = c.post(f"/submissions/{STUDENT3_SUBMISSION}/assist")
    assert resp.status_code == 302
    prompt = fake_claude.last_prompt()
    assert "<test_engine_results>" in prompt
    assert '"passed": false' in prompt
    assert "(hidden)" in prompt
    assert '"U"' not in prompt  # hidden test input withheld from the AI
    page = c.get(f"/submissions/{STUDENT3_SUBMISSION}").data.decode()
    assert "Using a stack (LIFO)" in page and "Groq AI" in page


def test_ai_cannot_change_test_results(app, fake_claude, query):
    before = query("SELECT test_case_id, passed FROM test_results WHERE submission_id = ? ORDER BY id",
                   (STUDENT3_SUBMISSION,))
    c = _login_student3(app)
    # Even if the AI claims everything passed, nothing about the stored results changes.
    fake_claude.set(ASSIST_TOOL, _assist_payload(
        failed_test_explanations=[], code_explanation="All tests passed! Score 100%."))
    c.post(f"/submissions/{STUDENT3_SUBMISSION}/assist")
    after = query("SELECT test_case_id, passed FROM test_results WHERE submission_id = ? ORDER BY id",
                  (STUDENT3_SUBMISSION,))
    assert before == after
    page = c.get(f"/submissions/{STUDENT3_SUBMISSION}").data.decode()
    passed = sum(r["passed"] for r in after)
    assert f"{passed}/4 tests passed" in page


def test_assistant_feedback_stored_as_qualitative(app, fake_claude, query):
    c = _login_student3(app)
    fake_claude.set(ASSIST_TOOL, _assist_payload())
    c.post(f"/submissions/{STUDENT3_SUBMISSION}/assist")
