def test_quality_report_structured_and_labelled(student, fake_claude, query):
    fake_claude.set(QUALITY_TOOL, {
        "summary": "Readable code with minor issues.",
        "findings": [
            {"category": "naming", "severity": "low", "line": 6, "title": "Name",
             "explanation": "x", "recommendation": "y"},
            {"category": "logic", "severity": "high", "line": 999, "title": "Possible bug",
             "explanation": "Visited list lookup is O(n).", "recommendation": "Use a set."},
            {"category": "unknown-cat", "severity": "info", "line": None, "title": "Note",
             "explanation": "a", "recommendation": "b"},
        ],
    })
    student.post("/submissions/1/quality")
    row = query("SELECT * FROM code_quality_reports WHERE submission_id = 1")[0]
    report = json.loads(row["payload_json"])
    assert row["source"] == "groq"
    assert [f["severity"] for f in report["findings"]] == ["high", "low", "info"]  # sorted by severity
    assert report["findings"][0]["line"] is None      # out-of-range line dropped
    assert report["findings"][2]["category"] == "other"
    page = student.get("/submissions/1").data.decode()
    assert "suggestions, not guaranteed defects" in page
    assert "generated by AI" in page


