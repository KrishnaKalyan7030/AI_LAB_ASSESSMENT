def test_rule_based_quality_checks(app, query):
    c = _login_student3(app)
    c.post(f"/submissions/{STUDENT3_SUBMISSION}/quality/rules")
    row = query("SELECT * FROM code_quality_reports WHERE submission_id = ?", (STUDENT3_SUBMISSION,))[0]
    report = json.loads(row["payload_json"])
    assert row["source"] == "rule_based" and row["model"] is None
    assert any("docstring" in f["title"] for f in report["findings"])
    assert "NOT an AI assessment" in report["summary"]
    page = c.get(f"/submissions/{STUDENT3_SUBMISSION}").data.decode()
    assert "Rule-based, not AI" in page and "not AI" in page


def test_quality_api_error_shows_message(student, fake_claude, query):
    fake_claude.set(QUALITY_TOOL, RateLimitError("429"))
    resp = student.post("/submissions/1/quality")
    page = student.get(resp.headers["Location"].split("#")[0]).data.decode()
    assert_rate_limited_message(page)
    assert query("SELECT COUNT(*) AS n FROM code_quality_reports")[0]["n"] == 0
