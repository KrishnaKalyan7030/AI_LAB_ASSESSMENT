"""Helpers shared by student and teacher routes."""
from __future__ import annotations

import json

from flask import abort, current_app, flash, g

from ..db import get_db
from ..repository import get_claude_service, save_feedback, store_viva_result, mark_viva_failed
from ..services import ai_features
from ..services.claude_service import ClaudeServiceError
from ..services.fallbacks import performance_rules
from ..services.performance import collect_student_stats


def is_teacher() -> bool:
    return g.user is not None and g.user["role"] == "teacher"


def load_attempt_or_404(attempt_id: int):
    """Students may only see their own attempts; teachers may see all."""
    row = get_db().execute(
        """SELECT a.*, q.question, q.subject, q.experiment, q.reference_answer, q.rubric,
                  q.key_concepts, q.max_score AS question_max, u.full_name AS student_name
           FROM viva_attempts a
           JOIN viva_questions q ON q.id = a.question_id
           JOIN users u ON u.id = a.student_id
           WHERE a.id = ?""",
        (attempt_id,),
    ).fetchone()
    if row is None or (not is_teacher() and row["student_id"] != g.user["id"]):
        abort(404)  # 404 (not 403) so students cannot probe which IDs exist
    return row


def load_submission_or_404(submission_id: int):
    row = get_db().execute(
        """SELECT s.*, a.title, a.description, a.function_name, a.experiment,
                  u.full_name AS student_name
           FROM submissions s
           JOIN assignments a ON a.id = s.assignment_id
           JOIN users u ON u.id = s.student_id
           WHERE s.id = ?""",
        (submission_id,),
    ).fetchone()
    if row is None or (not is_teacher() and row["student_id"] != g.user["id"]):
        abort(404)
    return row


def evaluate_attempt_with_ai(attempt) -> bool:
    """Run Feature A for a stored attempt. Returns True on success."""
    db = get_db()
    question = db.execute("SELECT * FROM viva_questions WHERE id = ?",
                          (attempt["question_id"],)).fetchone()
    service = get_claude_service(current_app.config)
    try:
        result = ai_features.assess_viva(service, question, attempt["answer"])
    except ClaudeServiceError as err:
        mark_viva_failed(db, attempt["id"], err.user_message)
        flash(err.user_message, "danger")
        return False
    store_viva_result(db, attempt, result.data, result.source, result.model)
    flash(f"Your answer was assessed by {service.display_name}.", "success")
    return True


def latest_summary(student_id: int):
    return get_db().execute(
        "SELECT * FROM ai_feedback WHERE student_id = ? AND kind = 'summary' "
        "ORDER BY id DESC LIMIT 1", (student_id,)
    ).fetchone()


def generate_summary(student_id: int, use_rules: bool = False) -> bool:
    """Feature E. Only the given student's own rows are aggregated."""
    db = get_db()
    stats = collect_student_stats(db, student_id)
    if stats["assessment_count"] == 0:
        flash("There are no assessed results yet, so no summary can be generated.", "warning")
        return False
    if use_rules:
        if not current_app.config.get("ALLOW_RULE_BASED_FALLBACK", True):
            abort(403)
        payload = performance_rules(stats)
        payload["stats"] = stats
        save_feedback(db, student_id, "summary", None, payload, "rule_based", None)
        flash("Rule-based (non-AI) summary generated.", "info")
        return True
    service = get_claude_service(current_app.config)
    try:
        result = ai_features.summarise_performance(service, stats)
    except ClaudeServiceError as err:
        flash(err.user_message, "danger")
        return False
    payload = dict(result.data)
    payload["stats"] = stats
    save_feedback(db, student_id, "summary", None, payload, result.source, result.model)
    flash(f"Performance summary generated by {service.display_name}.", "success")
    return True


def parse_payload(row):
    return json.loads(row["payload_json"]) if row else None
